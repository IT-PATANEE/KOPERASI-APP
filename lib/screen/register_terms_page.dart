class RegisterTermsPage extends StatefulWidget {
  const RegisterTermsPage({super.key});

  @override
  State<RegisterTermsPage> createState() => _RegisterTermsPageState();
}

class _RegisterTermsPageState extends State<RegisterTermsPage> {
  final ScrollController _scroll = ScrollController();
  bool _scrolledToBottom = false;
  bool _consentChecked = false;
  double _progress = 0.0; // 0..1 reading progress

  @override
  void initState() {
    super.initState();
    _scroll.addListener(_onScroll);
  }

  void _onScroll() {
    if (!_scroll.hasClients) return;
    final max = _scroll.position.maxScrollExtent;
    final offset = _scroll.offset.clamp(0.0, max);
    final p = max == 0 ? 1.0 : (offset / max);
    final atBottom = _scroll.position.pixels >= max - 8; // allow tiny tolerance
    if (mounted) {
      setState(() {
        _progress = p;
        _scrolledToBottom = atBottom;
      });
    }
  }

  bool get _canAccept => _scrolledToBottom && _consentChecked;

  Future<void> _confirmDecline() async {
    final ok = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: const Text('ยืนยันการปฏิเสธ?'),
        content: const Text(
          'คุณยังไม่ได้ยอมรับข้อกำหนดและเงื่อนไข หากปฏิเสธ คุณจะไม่สามารถดำเนินการต่อได้.',
        ),
        actions: [
          TextButton(
              onPressed: () => Navigator.pop(ctx, false),
              child: const Text('ยกเลิก')),
          FilledButton.tonal(
              onPressed: () => Navigator.pop(ctx, true),
              style: FilledButton.styleFrom(
                backgroundColor: Constants.greenColor, // สีพื้นหลังปุ่ม
                foregroundColor: Colors.white, // สีข้อความ
              ),
              child: const Text('ปฏิเสธ')),
        ],
      ),
    );
    if (ok == true && mounted) {
      Navigator.pop(context, false);
    }
  }

  void _onAccept() {
    Navigator.push(
      context,
      PageTransition(
        type: PageTransitionType.rightToLeft,
        child: const RegisterDataPage(),
        // child: const RegisterPage(),
        // duration: const Duration(milliseconds: 300), // ความเร็วแอนิเมชัน
      ),
    );
  }

  @override
  void dispose() {
    _scroll.removeListener(_onScroll);
    _scroll.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final media = MediaQuery.of(context);
    final w = media.size.width;
    final h = media.size.height;

    return Scaffold(
      backgroundColor: Colors.white,
      appBar: AppBar(
        backgroundColor: Colors.white, // พื้นหลังสีขาว
        surfaceTintColor: Colors.white, // ป้องกัน Material3 tint
        elevation: 0, // ไม่มีเงา
        centerTitle: true, // กึ่งกลาง
        title: const Text(
          'ข้อกำหนดและเงื่อนไขการใช้บริการ',
          style: TextStyle(color: Colors.black, fontWeight: FontWeight.bold),
        ),
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new, color: Colors.black),
          onPressed: () {
            Navigator.pop(context); // ย้อนกลับหน้าเดิม
          },
        ),
      ),
      body: Align(
        alignment: Alignment.topCenter,
        child: Column(
          children: [
            SizedBox(height: h * 0.01), // ระยะห่างด้านบน
            Padding(
              padding: EdgeInsets.symmetric(horizontal: w * 0.04),
              child: const StepProgressIndicator(
                currentStep: 1,
                totalSteps: 5,
              ),
            ),
            SizedBox(height: h * 0.01), // ช่องว่างระหว่าง Step กับกรอบ
            Container(
              margin: EdgeInsets.symmetric(horizontal: w * 0.04),
              constraints: BoxConstraints(
                maxHeight: h * 0.65, // ลดลงเพื่อเผื่อ Step Progress
                minWidth: w * 0.95,
              ),
              padding: EdgeInsets.symmetric(
                  horizontal: w * 0.04, vertical: h * 0.01),
              decoration: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(16),
                border: Border.all(color: Colors.grey.shade300),
                boxShadow: [
                  BoxShadow(
                    color: Colors.black.withOpacity(0.05),
                    blurRadius: 6,
                    offset: const Offset(0, 3),
                  ),
                ],
              ),
              // child: SingleChildScrollView(
