                      setState(() => _consentChecked = v ?? false),
                  activeColor: Constants.greenColor, // สีติ๊กถูก
                  checkColor: Colors.white, // สีเครื่องหมายถูก
                ),
                const Expanded(
                  child: Text(
                      'ฉันได้อ่านและยอมรับข้อกำหนดและเงื่อนไข รวมถึงนโยบายความเป็นส่วนตัว'),
